ANN_TYPE(IterateUnfoldWideState,Fuse)
data IterateUnfoldWideState o i a =
      IterateUnfoldWideOuter o (List a)
    | IterateUnfoldWideInner i (List a) (List a)

-- | Fusion enabled version of 'wideDfsConcatIterate'. The function argument
-- marks the leaves: when it returns @Just a@ for an element the 'Unfold' is
-- used to generate the children of the element from @a@; when it returns
-- 'Nothing', the element is a leaf. The traversal order is the
-- same as that of 'wideDfsConcatIterate'.
--
-- See 'unfoldIterateMaybe' for when fusion makes a difference.
--
-- A traversal of 'Either' elements, in which a @Left a@ element has children
-- generated from the seed @a@ and a @Right b@ element is a leaf:
--
-- >>> f = either Just (const Nothing)
-- >>> wideDfsUnfoldIterateLefts = Stream.wideDfsUnfoldIterate f
--
-- Example, list a directory tree:
--
-- >>> input = Stream.fromEffect (Left <$> Path.fromString ".")
-- >>> ls = wideDfsUnfoldIterateLefts (Dir.eitherReaderPaths id) input
--
-- /Pre-release/
{-# INLINE_NORMAL wideDfsUnfoldIterate #-}
wideDfsUnfoldIterate :: Monad m =>
       (b -> Maybe a)
    -> Unfold m a b
    -> Stream m b
    -> Stream m b
wideDfsUnfoldIterate f (Unfold istep inject) (Stream ostep ost) =
    Stream step (IterateUnfoldWideOuter ost (List []))

    where

    {-# INLINE push #-}
    push b rxs =
        case f b of
            Nothing -> rxs
            Just a -> a:rxs

    revOnto [] ys = ys
    revOnto (x:xs) ys = revOnto xs (x:ys)

    -- rxs: the seeds of the current stream in reverse order, reversed onto xs
    -- when the current stream ends. rxs1 is forced before it is stored in the
    -- state, otherwise a thunk is allocated for every element.
    {-# INLINE_LATE step #-}
    step gst (IterateUnfoldWideOuter o (List rxs)) = do
        r <- ostep (adaptState gst) o
        case r of
            Yield b s -> do
                let !rxs1 = push b rxs
                return $ Yield b (IterateUnfoldWideOuter s (List rxs1))
            Skip s -> return $ Skip (IterateUnfoldWideOuter s (List rxs))
            Stop ->
                case revOnto rxs [] of
                    (y:ys) -> do
                        i <- inject y
                        i `seq` return
                            $ Skip
                            $ IterateUnfoldWideInner i (List ys) (List [])
                    [] -> return Stop

    step _ (IterateUnfoldWideInner i (List xs) (List rxs)) = do
        r <- istep i
        case r of
            Yield b s -> do
                let !rxs1 = push b rxs
                return
                    $ Yield b
                    $ IterateUnfoldWideInner s (List xs) (List rxs1)
            Skip s ->
                return $ Skip (IterateUnfoldWideInner s (List xs) (List rxs))
            Stop ->
                case revOnto rxs xs of
                    (y:ys) -> do
                        i1 <- inject y
                        i1 `seq` return
                            $ Skip
                            $ IterateUnfoldWideInner i1 (List ys) (List [])
                    [] -> return Stop

