-- | Fusion enabled version of 'bfsConcatIterateRev'. Like
-- 'bfsUnfoldIterateMaybe' but the streams of a level are started in reverse
-- order. The traversal order is the same as that of 'bfsConcatIterateRev',
-- the resource use is the same as that of 'bfsUnfoldIterateMaybe'.
--
-- Use it when the order of the elements within a level does not matter. In a
-- benchmark summing the nodes of complete trees of 10^6 nodes held in memory,
-- it was 1.6 times faster than 'bfsUnfoldIterateMaybe' on a binary tree, 1.3
-- times on a 10-ary tree and the same on a 1000-ary tree, in which few seeds
-- are held.
--
-- A traversal of 'Either' elements, in which a @Left a@ element has children
-- generated from the seed @a@ and a @Right b@ element is a leaf:
--
-- >>> f = either Just (const Nothing)
-- >>> bfsUnfoldIterateLeftsRev = Stream.bfsUnfoldIterateRev f
--
-- /Pre-release/
{-# INLINE_NORMAL bfsUnfoldIterateRev #-}
bfsUnfoldIterateRev :: Monad m =>
       (b -> Maybe a)
    -> Unfold m a b
    -> Stream m b
    -> Stream m b
bfsUnfoldIterateRev f (Unfold istep inject) (Stream ostep ost) =
    Stream step (IterateUnfoldWideOuter ost (List []))

    where

    {-# INLINE push #-}
    push b rxs =
        case f b of
            Nothing -> rxs
            Just a -> a:rxs

    -- xs: the remaining seeds of the current level, rxs: the seeds of the next
    -- level in reverse order. rxs1 is forced before it is stored in the state,
    -- otherwise a thunk is allocated for every element.
    {-# INLINE_LATE step #-}
    step gst (IterateUnfoldWideOuter o (List rxs)) = do
        r <- ostep (adaptState gst) o
        case r of
            Yield b s -> do
                let !rxs1 = push b rxs
                return $ Yield b (IterateUnfoldWideOuter s (List rxs1))
            Skip s -> return $ Skip (IterateUnfoldWideOuter s (List rxs))
            Stop ->
                case rxs of
                    (y:ys) -> do
                        i <- inject y
                        i `seq` return
                            $ Skip
                            $ IterateUnfoldWideInner i (List ys) (List [])
                    [] -> return Stop

    step _ (IterateUnfoldWideInner i (List xs) (List rxs)) = do
        r <- istep i
        case r of
            Yield b s -> do
                let !rxs1 = push b rxs
                return
                    $ Yield b
                    $ IterateUnfoldWideInner s (List xs) (List rxs1)
            Skip s ->
                return $ Skip (IterateUnfoldWideInner s (List xs) (List rxs))
            Stop ->
                case xs of
                    (y:ys) -> do
                        i1 <- inject y
                        i1 `seq` return
                            $ Skip
                            $ IterateUnfoldWideInner i1 (List ys) (List rxs)
                    [] ->
                        case rxs of
                            (y:ys) -> do
                                i1 <- inject y
                                i1 `seq` return
                                    (Skip
                                        (IterateUnfoldWideInner
                                            i1 (List ys) (List [])))
                            [] -> return Stop

