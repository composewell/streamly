wideUnfoldIterateBatchPost :: Monad m =>
       (b -> Maybe a)
    -> Unfold m a b
    -> Stream m b
    -> Stream m b
wideUnfoldIterateBatchPost = wideUnfoldIterateBatchPostWith False

