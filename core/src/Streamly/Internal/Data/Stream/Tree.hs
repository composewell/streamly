RENAME(altBfsConcatIterate,wideDfsConcatIterateRev)

-- | Breadth first traversal (BFS) of a tree structure. The traversal proceeds
-- strictly level by level: one level of the tree finishes completely before
-- the next level starts. For the tree 1->[2,3], 2->[4], 3->[5], 4->[7],
-- 5->[6], the output is [1,2,3,4,5,7,6].
--
-- Because the streams of the nodes on a level are run to completion one after
-- another, they do not have to be kept open, but their elements are held in
-- memory to be expanded later. Only one stream is open at a time, the stream
-- of the node currently being expanded. The memory required is proportional
-- to the width of the widest level of the tree.
--
-- For example, during a directory traversal BFS has only one file descriptor
-- open but holds the entries of an entire level in memory. BFS is preferred
-- when the tree is deep and narrow, and DFS when the tree is shallow and wide.
--
-- BFS and wide DFS both have only one stream open at a time. In terms of
-- memory, wide DFS holds the pending elements along an entire path; BFS holds
-- the elements of an entire level of the tree.
--
-- Example, list a directory tree using BFS:
--
-- >>> f = either (Just . Dir.readEitherPaths id) (const Nothing)
-- >>> input = Stream.fromEffect (Left <$> Path.fromString ".")
-- >>> ls = Stream.bfsConcatIterate f input
--
-- /Pre-release/
{-# INLINE_NORMAL bfsConcatIterate #-}
bfsConcatIterate, concatIterateBfs :: Monad m =>
       (a -> Maybe (Stream m a))
    -> Stream m a
    -> Stream m a
bfsConcatIterate f stream = Stream step (stream, [], [])

    where

    {-# INLINE_LATE step #-}
    step gst (UnStream step1 st, xs, ys) = do
        r <- step1 (adaptState gst) st
        case r of
            Yield a s -> do
                let ys1 =
                        case f a of
                            Nothing -> ys
                            Just y -> y:ys
                return $ Yield a (Stream step1 s, xs, ys1)
            Skip s -> return $ Skip (Stream step1 s, xs, ys)
            Stop ->
                case xs of
                    (x:xs1) -> return $ Skip (x, xs1, ys)
                    [] ->
                        case reverse ys of
                            (x:xs1) -> return $ Skip (x, xs1, [])
                            [] -> return Stop

RENAME(concatIterateBfs,bfsConcatIterate)

-- | Like 'bfsConcatIterate' but the elements of each level are expanded in the
-- reverse of the order in which they were emitted, the last one first. The
-- tree is still traversed strictly level by level. For the tree 1->[2,3],
-- 2->[4], 3->[5], 4->[7], 5->[6], the output is [1,2,3,5,4,7,6];
-- 'bfsConcatIterate' gives [1,2,3,4,5,7,6]. This is faster than
-- 'bfsConcatIterate'. The resource use is the same as that of
-- 'bfsConcatIterate'.
--
{-# INLINE_NORMAL bfsConcatIterateRev #-}
bfsConcatIterateRev :: Monad m =>
       (a -> Maybe (Stream m a))
    -> Stream m a
    -> Stream m a
bfsConcatIterateRev f stream = Stream step (stream, [], [])

    where

    -- xs: the remaining streams of the current level, ys: the streams of the
    -- next level in reverse order.
    {-# INLINE_LATE step #-}
    step gst (UnStream step1 st, xs, ys) = do
        r <- step1 (adaptState gst) st
        case r of
            Yield a s -> do
                let ys1 =
                        case f a of
                            Nothing -> ys
                            Just y -> y:ys
                return $ Yield a (Stream step1 s, xs, ys1)
            Skip s -> return $ Skip (Stream step1 s, xs, ys)
            Stop ->
                case xs of
                    (x:xs1) -> return $ Skip (x, xs1, ys)
                    [] ->
                        case ys of
                            (x:xs1) -> return $ Skip (x, xs1, [])
                            [] -> return Stop

-- | Depth first traversal (DFS) of a tree structure. The traversal opens the
-- stream of a node, takes its first child, then the first child of that
-- child, and so on until it reaches a leaf node; it then continues with the
-- next sibling of the leaf. For the tree 1->[2,3], 2->[4], 3->[5], 4->[7],
-- 5->[6], the output is [1,2,4,7,3,5,6].
--
-- Because the stream of each node on the current path is unfinished, the
-- streams of all the nodes on the path have to be kept open; the number of
-- open streams and the memory used are proportional to the depth of the
-- current path. For example, during a directory traversal DFS keeps a file
-- descriptor open for each directory on the current path. DFS is preferred
-- when the tree is shallow and wide, and BFS when the tree is deep and narrow.
--
-- Example, list a directory tree using DFS:
--
-- >>> f = either (Just . Dir.readEitherPaths id) (const Nothing)
-- >>> input = Stream.fromEffect (Left <$> Path.fromString ".")
-- >>> ls = Stream.concatIterate f input
--
-- This is equivalent to using @concatIterateWith StreamK.append@.
--
-- /Pre-release/
{-# INLINE_NORMAL concatIterate #-}
concatIterate, concatIterateDfs :: Monad m =>
       (a -> Maybe (Stream m a))
    -> Stream m a
    -> Stream m a
concatIterate f stream = Stream step (stream, [])

    where

    {-# INLINE_LATE step #-}
    step gst (UnStream step1 st, xs) = do
        r <- step1 (adaptState gst) st
        case r of
            Yield a s -> do
                let st1 =
                        case f a of
                            Nothing -> (Stream step1 s, xs)
                            Just x -> (x, Stream step1 s:xs)
                return $ Yield a st1
            Skip s -> return $ Skip (Stream step1 s, xs)
            Stop ->
                case xs of
                    (y:ys) -> return $ Skip (y, ys)
                    [] -> return Stop

RENAME(concatIterateDfs,concatIterate)

-- Specializing the list in the Unfold state does not help performance and also
-- blows up the memory required for compilation. Blocking the list cuts the
-- noise helps specialize on other types that matter.
ANN_TYPE(List,NoSpecConstr)
newtype List a = List [a]

ANN_TYPE(IterateUnfoldState,Fuse)
data IterateUnfoldState o i =
      IterateUnfoldOuter o
    | IterateUnfoldInner o i (List i)

-- | Fusion enabled version of 'concatIterate'. The function argument marks the
-- leaves: when it returns @Just a@ for an element, the 'Unfold' is used to
-- generate the children of the element from @a@; when it returns 'Nothing',
-- the element is a leaf. The traversal order and the resource use are the same
-- as those of 'concatIterate'.
--
-- The 'Unfold' fuses with the traversal loop. This makes 'unfoldIterateMaybe'
-- faster than 'concatIterate' when the cost of the traversal itself dominates
-- the workload, for example, when traversing a tree held in memory. In a
-- benchmark summing the nodes of complete binary, 10-ary and 1000-ary trees of
-- 10^5 and 10^6 nodes held in memory, 'unfoldIterateMaybe' was 12 to 18 times
-- faster than 'concatIterate'. When processing an element costs much more
-- than the traversal, for example, reading a directory, the difference is
-- negligible: listing a tree of 3906 directories took the same time, about
-- 31 ms, with either.
--
-- A traversal of 'Either' elements, in which a @Left a@ element has children
-- generated from the seed @a@ and a @Right b@ element is a leaf:
--
-- >>> f = either Just (const Nothing)
-- >>> unfoldIterateLefts = Stream.unfoldIterateMaybe f
--
-- Example, list a directory tree using DFS:
--
-- >>> input = Stream.fromEffect (Left <$> Path.fromString ".")
-- >>> ls = unfoldIterateLefts (Dir.eitherReaderPaths id) input
--
-- /Pre-release/
{-# INLINE_NORMAL unfoldIterateMaybe #-}
unfoldIterateMaybe :: Monad m =>
       (b -> Maybe a)
    -> Unfold m a b
    -> Stream m b
    -> Stream m b
unfoldIterateMaybe f (Unfold istep inject) (Stream ostep ost) =
    Stream step (IterateUnfoldOuter ost)

    where

    {-# INLINE_LATE step #-}
    step gst (IterateUnfoldOuter o) = do
        r <- ostep (adaptState gst) o
        case r of
            Yield b s ->
                case f b of
                    Nothing -> return $ Yield b (IterateUnfoldOuter s)
                    Just a -> do
                        i <- inject a
                        i `seq` return
                            $ Yield b (IterateUnfoldInner s i (List []))
            Skip s -> return $ Skip (IterateUnfoldOuter s)
            Stop -> return Stop

    step _ (IterateUnfoldInner o i (List ii)) = do
        r <- istep i
        case r of
            Yield b s ->
                case f b of
                    Nothing ->
                        return $ Yield b (IterateUnfoldInner o s (List ii))
                    Just a -> do
                        i1 <- inject a
                        i1 `seq` return
                            $ Yield b (IterateUnfoldInner o i1 (List (s:ii)))
            Skip s -> return $ Skip (IterateUnfoldInner o s (List ii))
            Stop ->
                case ii of
                    (y:ys) -> return $ Skip (IterateUnfoldInner o y (List ys))
                    [] -> return $ Skip (IterateUnfoldOuter o)

